import solc from "solc"; import ganache from "ganache"; import { ethers } from "ethers"; import fs from "fs";
const src = fs.readFileSync("VotingV2.sol", "utf8");
const out = JSON.parse(solc.compile(JSON.stringify({ language: "Solidity", sources: { "VotingV2.sol": { content: src } },
  settings: { optimizer: { enabled: false }, evmVersion: "shanghai", outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } } } })));
(out.errors || []).forEach((e) => console.log(e.severity, e.formattedMessage.split("\n")[0]));
const C = out.contracts["VotingV2.sol"].VotingV2; fs.writeFileSync("abi.json", JSON.stringify(C.abi, null, 1));
console.log("version", solc.version(), "bytecode bytes", C.evm.bytecode.object.length / 2);
const provider = new ethers.BrowserProvider(ganache.provider({ logging: { quiet: true }, chain: { hardfork: "shanghai" } }));
const [a, b, c] = await Promise.all([0, 1, 2].map((i) => provider.getSigner(i)));
const v = await (await new ethers.ContractFactory(C.abi, C.evm.bytecode.object, a).deploy()).waitForDeployment();
let pass = 0, fail = 0;
const ok = (n, x) => { x ? pass++ : (fail++, console.log("FAIL", n)); };
const rev = async (n, p, msg) => { try { await (await p).wait?.(); ok(n + " (should revert)", false); } catch (e) { ok(n, (e.shortMessage || e.message).includes(msg) || (e.info?.error?.message || "").includes(msg) || String(e).includes(msg)); } };
const now = (await provider.getBlock("latest")).timestamp;
await (await v.createPoll("Best editor?", "Tech", ["VS Code", "Vim", "Emacs"], now + 3600)).wait();
ok("count 1", (await v.pollCount()) === 1n);
const p0 = await v.getPoll(0); ok("createdAt set", p0.createdAt > 0n); ok("creator", p0.creator === a.address); ok("view id", p0.id === 0n);
await rev("too few options", v.createPoll("Q", "Tech", ["only"], now + 3600), "2 to 10 options");
await rev("too many options", v.createPoll("Q", "Tech", Array.from({ length: 11 }, (_, i) => "o" + i), now + 3600), "2 to 10 options");
await rev("long title", v.createPoll("x".repeat(201), "Tech", ["a", "b"], now + 3600), "Title must be");
await rev("empty title", v.createPoll("", "Tech", ["a", "b"], now + 3600), "Title must be");
await rev("long option", v.createPoll("Q", "Tech", ["a", "b".repeat(101)], now + 3600), "Each option");
await rev("empty option", v.createPoll("Q", "Tech", ["a", ""], now + 3600), "Each option");
await rev("long category", v.createPoll("Q", "x".repeat(33), ["a", "b"], now + 3600), "Category must be");
await rev("past end", v.createPoll("Q", "Tech", ["a", "b"], now - 10), "End time must be in the future");
await rev("over a year", v.createPoll("Q", "Tech", ["a", "b"], now + 366 * 86400), "at most a year");
await (await v.connect(b).vote(0, 1)).wait();
await rev("double vote", v.connect(b).vote(0, 2), "Already voted");
await rev("bad option", v.connect(c).vote(0, 9), "No such option");
await rev("no poll", v.vote(5, 0), "No such poll");
ok("votes", (await v.getVotes(0)).join() === "0,1,0"); ok("votedFor", (await v.votedFor(0, b.address)) === 1n); ok("hasVoted", await v.hasVoted(0, b.address));
await rev("not creator close", v.connect(b).closePoll(0), "Only the creator");
await (await v.closePoll(0)).wait(); ok("closed", !(await v.getPoll(0)).isOpen);
await rev("vote after close", v.connect(c).vote(0, 0), "Poll is closed");
await rev("close twice", v.closePoll.staticCall(0), "Already closed"); try { await (await v.closePoll(0)).wait(); console.log("FAIL close twice: did not revert"); } catch (e) { console.log("close twice err:", (e.shortMessage||"") + " / " + (e.info?.error?.message||"") + " / " + (e.reason||"")); }
ok("votes untouched after close", (await v.getVotes(0)).join() === "0,1,0");
for (let i = 0; i < 59; i++) await (await v.createPoll("Poll " + i, "Fun", ["a", "b"], now + 7200)).wait();
ok("60 polls", (await v.pollCount()) === 60n);
const pg = await v.getPolls(0, 500); ok("page capped at 50", pg.length === 50);
const pg2 = await v.getPolls(50, 50); ok("last page 10", pg2.length === 10 && pg2[9].id === 59n);
ok("past end empty", (await v.getPolls(60, 5)).length === 0);
await provider.send("evm_increaseTime", [7300]); await provider.send("evm_mine", []);
await rev("vote after end time", v.connect(c).vote(1, 0), "Poll is closed");
const gas = await v.getPolls.estimateGas(0, 50); console.log("getPolls(0,50) gas (free view call):", gas.toString());
console.log(`PASS ${pass}  FAIL ${fail}`);
process.exit(0);
